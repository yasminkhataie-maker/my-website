def image_size(path):
    """Width and height of a WebP, PNG or JPEG file, for the img width/height attributes."""
    data = path.read_bytes()[:64 * 1024]
    if data[:4] == b"RIFF" and data[8:12] == b"WEBP":
        chunk = data[12:16]
        if chunk == b"VP8X":
            return 1 + int.from_bytes(data[24:27], "little"), 1 + int.from_bytes(data[27:30], "little")
        if chunk == b"VP8 ":
            return int.from_bytes(data[26:28], "little") & 0x3FFF, int.from_bytes(data[28:30], "little") & 0x3FFF
        if chunk == b"VP8L":
            bits = int.from_bytes(data[21:25], "little")
            return (bits & 0x3FFF) + 1, ((bits >> 14) & 0x3FFF) + 1
    if data[:8] == b"\x89PNG\r\n\x1a\n":
        return int.from_bytes(data[16:20], "big"), int.from_bytes(data[20:24], "big")
    if data[:2] == b"\xff\xd8":
        i = 2
        while i < len(data) - 9:
            if data[i] != 0xFF:
                i += 1
                continue
            marker, length = data[i + 1], int.from_bytes(data[i + 2:i + 4], "big")
            if marker in (0xC0, 0xC1, 0xC2):
                return int.from_bytes(data[i + 7:i + 9], "big"), int.from_bytes(data[i + 5:i + 7], "big")
            i += 2 + length
    sys.exit(f"{path}: could not read image size")


def load_services():
    data = yaml.safe_load(SERVICES_FILE.read_text(encoding="utf-8")) or {}
    services = data.get("services") or []
    for s in services:
        missing = [f for f in SERVICE_FIELDS if not s.get(f)]
        if missing:
            sys.exit(f"{SERVICES_FILE}: service {s.get('slug')!r} is missing: {', '.join(missing)}")
        if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", s["slug"]) or s["slug"] in ("insights", "assets"):
            sys.exit(f"{SERVICES_FILE}: invalid slug {s['slug']!r}")
        for item in s["how"]:
            if not isinstance(item, dict) or not item.get("label") or not item.get("text"):
                sys.exit(f"{SERVICES_FILE}: {s['slug']}: each 'how' item needs a label and text")
        for item in s["faq"]:
            if not isinstance(item, dict) or not item.get("q") or not item.get("a"):
                sys.exit(f"{SERVICES_FILE}: {s['slug']}: each faq entry needs a 'q' and an 'a'")
        image_path = ROOT / str(s["image"]).lstrip("/")
        if not image_path.is_file():
            sys.exit(f"{SERVICES_FILE}: {s['slug']}: image not found: {s['image']}")
        s["image_size"] = image_size(image_path)
        s["url"] = f"/{s['slug']}/"
    for key in ("slug", "tag"):
        values = [s[key] for s in services]
        dupes = {v for v in values if values.count(v) > 1}
        if dupes:
            sys.exit(f"{SERVICES_FILE}: duplicate {key}(s): {', '.join(sorted(dupes))}")
    return services


def load_posts(include_drafts, services):
    service_tags = {s["tag"] for s in services}
    posts = []
    for path in sorted(CONTENT_DIR.glob("*.md")):
        if path.name.lower() == "readme.md" or path.name.startswith("_"):
            continue
        raw = path.read_text(encoding="utf-8")
        m = re.match(r"^---\s*\n(.*?)\n---\s*\n(.*)$", raw, re.S)
        if not m:
            sys.exit(f"{path}: missing front matter (--- ... ---) at the top")
        meta = yaml.safe_load(m.group(1)) or {}
        if meta.get("draft") and not include_drafts:
            continue
        missing = [f for f in REQUIRED_FIELDS if not meta.get(f)]
        if missing:
            sys.exit(f"{path}: missing front matter field(s): {', '.join(missing)}")
        slug = str(meta.get("slug") or path.stem).strip().strip("/")
        if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", slug):
            sys.exit(f"{path}: slug must be lowercase words joined by hyphens, got {slug!r}")
        date = to_date(meta["date"], "date", path)
        updated = to_date(meta.get("updated") or meta["date"], "updated", path)
        faq = meta.get("faq") or []
        for item in faq:
            if not isinstance(item, dict) or not item.get("q") or not item.get("a"):
                sys.exit(f"{path}: each faq entry needs a 'q' and an 'a'")
        service = str(meta.get("service") or "").strip()
        if service and service not in service_tags:
            sys.exit(f"{path}: service must be one of {', '.join(sorted(service_tags))}, got {service!r}")
        body_html = markdown.markdown(m.group(2), extensions=["extra", "sane_lists"])
        if re.search(r"<h1[\s>]", body_html):
            sys.exit(f"{path}: the article body must not contain a level-1 heading (#); "
                     "the title is the H1. Use ## and ### in the body.")
        posts.append({
            "title": str(meta["title"]).strip(),
            "slug": slug,
            "description": str(meta["description"]).strip(),
            "short_answer": str(meta["short_answer"]).strip(),
            "date": date,
            "updated": max(updated, date),
            "tags": [str(t).strip() for t in (meta.get("tags") or [])],
            "image": str(meta.get("image") or DEFAULT_IMAGE),
            "faq": faq,
            "service": service,
            "body": body_html,
            "draft": bool(meta.get("draft")),
            "url": f"/insights/{slug}/",
        })
    slugs = [p["slug"] for p in posts]
    dupes = {s for s in slugs if slugs.count(s) > 1}
    if dupes:
        sys.exit(f"duplicate slug(s): {', '.join(sorted(dupes))}")
    posts.sort(key=lambda p: (p["date"], p["slug"]), reverse=True)
    return posts


def related_posts(post, posts, limit=3):
    tags = set(post["tags"])
    if not tags:
        return []
    return [p for p in posts if p is not post and tags & set(p["tags"])][:limit]


