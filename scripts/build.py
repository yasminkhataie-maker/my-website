def esc(text):
    return html.escape(str(text), quote=True)


def typo(text):
    """Typographic apostrophes for visible copy, matching the rest of the site."""
    return str(text).strip().replace("'", "\u2019")


def to_date(value, field, source):
    if isinstance(value, dt.datetime):
        return value.date()
    if isinstance(value, dt.date):
        return value
    try:
        return dt.date.fromisoformat(str(value))
    except ValueError:
        sys.exit(f"{source}: '{field}' must be a date like 2026-10-02, got {value!r}")


def human_date(d):
    return f"{d.day} {d.strftime('%B %Y')}"


def abs_url(path):
    return path if path.startswith("http") else SITE_URL + path


def git_date(path):
    """Last commit date of a file, or today if it has uncommitted changes."""
    rel = path.relative_to(ROOT)
    try:
        dirty = subprocess.run(["git", "status", "--porcelain", "--", str(rel)], cwd=ROOT,
                               capture_output=True, text=True, check=True).stdout.strip()
        if not dirty:
            out = subprocess.run(["git", "log", "-1", "--format=%cs", "--", str(rel)], cwd=ROOT,
                                 capture_output=True, text=True, check=True).stdout.strip()
            if out:
                return dt.date.fromisoformat(out)
    except (subprocess.CalledProcessError, FileNotFoundError):
        pass
    return dt.date.today()


def json_ld(data):
    body = json.dumps(data, indent=2, ensure_ascii=False)
    # keep "</script>" sequences inside strings from closing the tag
    body = body.replace("</", "<\\/")
    return f'<script type="application/ld+json">\n{body}\n</script>'


def replace_block(text, name, content):
    """Replace every <!-- BUILD:name ... --> ... <!-- /BUILD:name --> block."""
    pattern = re.compile(r"(<!-- BUILD:%s(?: [^>]*)? -->)(.*?)([ \t]*<!-- /BUILD:%s -->)" % (name, name), re.S)
    if not pattern.search(text):
        sys.exit(f"index.html: missing <!-- BUILD:{name} --> block")
    sep = "\n" if "\n" in content else ""
    def fill(m):
        indent = m.group(3)[:len(m.group(3)) - len(m.group(3).lstrip())] if sep else ""
        return m.group(1) + sep + indent + content + sep + m.group(3)
    return pattern.sub(fill, text)


