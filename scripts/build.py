def render_feed(posts):
    def rfc822(d):
        return format_datetime(dt.datetime(d.year, d.month, d.day, 9, 0, tzinfo=dt.timezone.utc))

    items = "\n".join(f"""    <item>
      <title>{esc(p['title'])}</title>
      <link>{abs_url(p['url'])}</link>
      <guid isPermaLink="true">{abs_url(p['url'])}</guid>
      <pubDate>{rfc822(p['date'])}</pubDate>
      <description>{esc(p['description'])}</description>
    </item>""" for p in posts)
    build_date = rfc822(posts[0]["updated"]) if posts else rfc822(dt.date(2026, 10, 2))
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom">
  <channel>
    <title>Veloxitas Insights</title>
    <link>{SITE_URL}/insights/</link>
    <description>{esc(INSIGHTS_INTRO)}</description>
    <language>en</language>
    <lastBuildDate>{build_date}</lastBuildDate>
    <atom:link href="{SITE_URL}/insights/feed.xml" rel="self" type="application/rss+xml"/>
{items}
  </channel>
</rss>
"""


def render_sitemap(posts, services, home_lastmod, services_lastmod):
    insights_lastmod = max([home_lastmod] + [p["updated"] for p in posts]) if posts else home_lastmod
    urls = [(SITE_URL + "/", home_lastmod)]
    urls += [(abs_url(s["url"]), services_lastmod) for s in services]
    urls += [(SITE_URL + "/insights/", insights_lastmod)]
    urls += [(abs_url(p["url"]), p["updated"]) for p in posts]
    entries = "\n".join(f"""  <url>
    <loc>{esc(loc)}</loc>
    <lastmod>{lastmod.isoformat()}</lastmod>
  </url>""" for loc, lastmod in urls)
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
{entries}
</urlset>
"""


def homepage_faq_jsonld(index_html):
    section = re.search(r'<section class="faqs" id="faqs">(.*?)</section>', index_html, re.S)
    if not section:
        sys.exit("index.html: FAQ section not found")
    pairs = re.findall(r'<div class="faq-item">\s*<h3>(.*?)</h3>\s*<p>(.*?)</p>\s*</div>', section.group(1), re.S)
    if not pairs:
        sys.exit("index.html: no FAQ items found")

    def text(fragment):
        return " ".join(html.unescape(re.sub(r"<[^>]+>", "", fragment)).split())

    return json_ld({
        "@context": "https://schema.org",
        "@type": "FAQPage",
        "mainEntity": [{
            "@type": "Question",
            "name": text(q),
            "acceptedAnswer": {"@type": "Answer", "text": text(a)},
        } for q, a in pairs],
    })


