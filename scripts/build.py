# ---------------------------------------------------------------- helpers

def esc(text):
    return html.escape(str(text), quote=True)


def to_date(value, field, source):
    if isinstance(value, dt.datetime):
        return value.date()
    if isinstance(value, dt.date):
        return value
    try:
        return dt.date.fromisoformat(str(value))
    except ValueError:
        sys.exit(f"{source}: '{field}' must be a date like 2026-10-02, got {value!r}")


def human_date(d):
    return f"{d.day} {d.strftime('%B %Y')}"


def abs_url(path):
    return path if path.startswith("http") else SITE_URL + path


def git_date(path):
    """Last commit date of a file, or today if it has uncommitted changes."""
    rel = path.relative_to(ROOT)
    try:
        dirty = subprocess.run(["git", "status", "--porcelain", "--", str(rel)], cwd=ROOT,
                               capture_output=True, text=True, check=True).stdout.strip()
        if not dirty:
            out = subprocess.run(["git", "log", "-1", "--format=%cs", "--", str(rel)], cwd=ROOT,
                                 capture_output=True, text=True, check=True).stdout.strip()
            if out:
                return dt.date.fromisoformat(out)
    except (subprocess.CalledProcessError, FileNotFoundError):
        pass
    return dt.date.today()


def json_ld(data):
    body = json.dumps(data, indent=2, ensure_ascii=False)
    # keep "</script>" sequences inside strings from closing the tag
    body = body.replace("</", "<\\/")
    return f'<script type="application/ld+json">\n{body}\n</script>'


def replace_block(text, name, content):
    """Replace every <!-- BUILD:name ... --> ... <!-- /BUILD:name --> block."""
    pattern = re.compile(r"(<!-- BUILD:%s(?: [^>]*)? -->)(.*?)(<!-- /BUILD:%s -->)" % (name, name), re.S)
    if not pattern.search(text):
        sys.exit(f"index.html: missing <!-- BUILD:{name} --> block")
    sep = "\n" if "\n" in content else ""
    return pattern.sub(lambda m: m.group(1) + sep + content + sep + m.group(3), text)


# ---------------------------------------------------------------- content

def load_posts(include_drafts):
    posts = []
    for path in sorted(CONTENT_DIR.glob("*.md")):
        if path.name.lower() == "readme.md" or path.name.startswith("_"):
            continue
        raw = path.read_text(encoding="utf-8")
        m = re.match(r"^---\s*\n(.*?)\n---\s*\n(.*)$", raw, re.S)
        if not m:
            sys.exit(f"{path}: missing front matter (--- ... ---) at the top")
        meta = yaml.safe_load(m.group(1)) or {}
        if meta.get("draft") and not include_drafts:
            continue
        missing = [f for f in REQUIRED_FIELDS if not meta.get(f)]
        if missing:
            sys.exit(f"{path}: missing front matter field(s): {', '.join(missing)}")
        slug = str(meta.get("slug") or path.stem).strip().strip("/")
        if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", slug):
            sys.exit(f"{path}: slug must be lowercase words joined by hyphens, got {slug!r}")
        date = to_date(meta["date"], "date", path)
        updated = to_date(meta.get("updated") or meta["date"], "updated", path)
        faq = meta.get("faq") or []
        for item in faq:
            if not isinstance(item, dict) or not item.get("q") or not item.get("a"):
                sys.exit(f"{path}: each faq entry needs a 'q' and an 'a'")
        body_html = markdown.markdown(m.group(2), extensions=["extra", "sane_lists"])
        if re.search(r"<h1[\s>]", body_html):
            sys.exit(f"{path}: the article body must not contain a level-1 heading (#); "
                     "the title is the H1. Use ## and ### in the body.")
        posts.append({
            "title": str(meta["title"]).strip(),
            "slug": slug,
            "description": str(meta["description"]).strip(),
            "short_answer": str(meta["short_answer"]).strip(),
            "date": date,
            "updated": max(updated, date),
            "tags": [str(t).strip() for t in (meta.get("tags") or [])],
            "image": str(meta.get("image") or DEFAULT_IMAGE),
            "faq": faq,
            "body": body_html,
            "draft": bool(meta.get("draft")),
            "url": f"/insights/{slug}/",
        })
    slugs = [p["slug"] for p in posts]
    dupes = {s for s in slugs if slugs.count(s) > 1}
    if dupes:
        sys.exit(f"duplicate slug(s): {', '.join(sorted(dupes))}")
    posts.sort(key=lambda p: (p["date"], p["slug"]), reverse=True)
    return posts


def related_posts(post, posts, limit=3):
    tags = set(post["tags"])
    if not tags:
        return []
    return [p for p in posts if p is not post and tags & set(p["tags"])][:limit]


