def render_feed(posts):
    def rfc822(d):
        return format_datetime(dt.datetime(d.year, d.month, d.day, 9, 0, tzinfo=dt.timezone.utc))

    items = "\n".join(f"""    <item>
      <title>{esc(p['title'])}</title>
      <link>{abs_url(p['url'])}</link>
      <guid isPermaLink="true">{abs_url(p['url'])}</guid>
      <pubDate>{rfc822(p['date'])}</pubDate>
      <description>{esc(p['description'])}</description>
    </item>""" for p in posts)
    build_date = rfc822(posts[0]["updated"]) if posts else rfc822(dt.date(2026, 10, 2))
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom">
  <channel>
    <title>Veloxitas Insights</title>
    <link>{SITE_URL}/insights/</link>
    <description>{esc(INSIGHTS_INTRO)}</description>
    <language>en</language>
    <lastBuildDate>{build_date}</lastBuildDate>
    <atom:link href="{SITE_URL}/insights/feed.xml" rel="self" type="application/rss+xml"/>
{items}
  </channel>
</rss>
"""


def render_sitemap(posts, home_lastmod):
    insights_lastmod = max([home_lastmod] + [p["updated"] for p in posts]) if posts else home_lastmod
    urls = [(SITE_URL + "/", home_lastmod), (SITE_URL + "/insights/", insights_lastmod)]
    urls += [(abs_url(p["url"]), p["updated"]) for p in posts]
    entries = "\n".join(f"""  <url>
    <loc>{esc(loc)}</loc>
    <lastmod>{lastmod.isoformat()}</lastmod>
  </url>""" for loc, lastmod in urls)
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
{entries}
</urlset>
"""


def homepage_faq_jsonld(index_html):
    section = re.search(r'<section class="faqs" id="faqs">(.*?)</section>', index_html, re.S)
    if not section:
        sys.exit("index.html: FAQ section not found")
    pairs = re.findall(r'<div class="faq-item">\s*<h3>(.*?)</h3>\s*<p>(.*?)</p>\s*</div>', section.group(1), re.S)
    if not pairs:
        sys.exit("index.html: no FAQ items found")

    def text(fragment):
        return " ".join(html.unescape(re.sub(r"<[^>]+>", "", fragment)).split())

    return json_ld({
        "@context": "https://schema.org",
        "@type": "FAQPage",
        "mainEntity": [{
            "@type": "Question",
            "name": text(q),
            "acceptedAnswer": {"@type": "Answer", "text": text(a)},
        } for q, a in pairs],
    })


# ---------------------------------------------------------------- main

def build(out_dir, include_drafts):
    posts = load_posts(include_drafts)
    files = {}

    index_path = ROOT / "index.html"
    index_html = index_path.read_text(encoding="utf-8")
    index_html = replace_block(index_html, "FAQ_JSONLD", homepage_faq_jsonld(index_html))
    index_html = replace_block(index_html, "NAV_INSIGHTS", nav_insights_link(bool(posts)))
    files["index.html"] = index_html

    files["insights/index.html"] = render_index(posts)
    files["insights/feed.xml"] = render_feed(posts)
    for p in posts:
        files[f"insights/{p['slug']}/index.html"] = render_post(p, posts)
    files["sitemap.xml"] = render_sitemap(posts, git_date(index_path))

    # article folders generated earlier whose source is gone (or became a draft)
    stale = []
    insights_out = out_dir / "insights"
    if insights_out.is_dir():
        for d in insights_out.iterdir():
            page_file = d / "index.html"
            if d.is_dir() and f"insights/{d.name}/index.html" not in files and page_file.is_file() \
                    and GENERATED_MARK in page_file.read_text(encoding="utf-8"):
                stale.append(d)
    return files, stale


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="exit 1 if generated files are out of date")
    parser.add_argument("--drafts", action="store_true", help="include draft articles (preview only)")
    parser.add_argument("--out", type=Path, default=ROOT, help="output directory (default: repo root)")
    args = parser.parse_args()

    out_dir = args.out.resolve()
    if args.drafts and out_dir == ROOT:
        sys.exit("--drafts writes unpublished articles; use it with --out <preview folder>")

    if out_dir != ROOT and not args.check:
        # preview build: start from a copy of the static site so pages render
        shutil.copytree(ROOT, out_dir, dirs_exist_ok=True,
                        ignore=shutil.ignore_patterns(".git", ".github", "content", "scripts",
                                                      "backup-original-design"))

    files, stale = build(out_dir, args.drafts)
    changed = [rel for rel, content in files.items()
               if not (out_dir / rel).is_file() or (out_dir / rel).read_text(encoding="utf-8") != content]

    if args.check:
        problems = changed + [f"{d.relative_to(out_dir)}/ (stale)" for d in stale]
        if problems:
            print("Out of date (run python3 scripts/build.py):\n  " + "\n  ".join(problems))
            sys.exit(1)
        print("Generated files are up to date.")
        return

    for rel in changed:
        target = out_dir / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(files[rel], encoding="utf-8")
        print(f"wrote {rel}")
    for d in stale:
        shutil.rmtree(d)
        print(f"removed {d.relative_to(out_dir)}/")
    if not changed and not stale:
        print("Nothing to do: generated files are up to date.")


if __name__ == "__main__":
    main()
